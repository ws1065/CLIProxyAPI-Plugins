// TestApplyConfigValuesAgainstRealConfig runs the management save path against a
// copy of the production config.yaml. It proves the splice keeps the rest of the
// document byte-identical, writes a backup, and takes effect in-process.
func TestApplyConfigValuesAgainstRealConfig(t *testing.T) {
	realConfig := "../../config.yaml"
	if _, err := os.Stat(realConfig); err != nil {
		t.Skipf("real config not available: %v", err)
	}
	original, err := os.ReadFile(realConfig)
	if err != nil {
		t.Fatalf("read real config: %v", err)
	}
	dir := t.TempDir()
	work := filepath.Join(dir, "config.yaml")
	if err := os.WriteFile(work, original, 0o600); err != nil {
		t.Fatalf("seed work config: %v", err)
	}

	// Seed config_path in-process only. Going through applyConfigValues would
	// resolve the real config.yaml (the host's CWD) and write to it, which is
	// exactly what this test must never do.
	var doc struct {
		Plugins struct {
			Configs map[string]yaml.Node `yaml:"configs"`
		} `yaml:"plugins"`
	}
	if err := yaml.Unmarshal(original, &doc); err != nil {
		t.Fatalf("parse original: %v", err)
	}
	node, ok := doc.Plugins.Configs[pluginID]
	if !ok {
		t.Skipf("real config has no plugins.configs.%s block", pluginID)
	}
	block, err := yaml.Marshal(&node)
	if err != nil {
		t.Fatalf("marshal plugin block: %v", err)
	}
	var blockMap map[string]any
	if err := yaml.Unmarshal(block, &blockMap); err != nil {
		t.Fatalf("parse plugin block: %v", err)
	}
	blockMap["config_path"] = work
	seeded, err := yaml.Marshal(blockMap)
	if err != nil {
		t.Fatalf("marshal seeded block: %v", err)
	}
	if err := configureRaw(seeded); err != nil {
		t.Fatalf("configureRaw seed: %v", err)
	}
	t.Cleanup(func() {
		if err := configureRaw(block); err != nil {
			t.Errorf("restore original plugin state: %v", err)
		}
	})

	body, err := json.Marshal(map[string]any{"official_min_score": 7})
	if err != nil {
		t.Fatalf("marshal body: %v", err)
	}
	if resolved := resolveConfigFile(); resolved != work {
		t.Fatalf("refusing to run: resolved config %q is not the temp copy %q", resolved, work)
	}
	if _, err := applyConfigValues(body); err != nil {
		t.Fatalf("applyConfigValues: %v", err)
	}
	if after, errRead := os.ReadFile(realConfig); errRead != nil {
		t.Fatalf("re-read real config: %v", errRead)
	} else if string(after) != string(original) {
		t.Fatalf("test mutated the real %s", realConfig)
	}

	if got := currentConfig().OfficialMinScore; got != 7 {
		t.Errorf("in-process score = %d, want 7", got)
	}
	written, err := os.ReadFile(work)
	if err != nil {
		t.Fatalf("read written config: %v", err)
	}
	if _, err := os.Stat(work + ".bak-before-" + pluginID); err != nil {
		t.Errorf("backup not created: %v", err)
	}
	if !strings.Contains(string(written), "official_min_score: 7") {
		t.Errorf("written config does not carry the new value")
	}

	// Everything outside the plugin block must survive untouched.
	var before, after map[string]any
	if err := yaml.Unmarshal(original, &before); err != nil {
		t.Fatalf("parse original: %v", err)
	}
	if err := yaml.Unmarshal(written, &after); err != nil {
		t.Fatalf("parse written: %v", err)
	}
	for _, key := range []string{"port", "api-keys", "openai-compatibility", "management", "remote-management"} {
		if _, ok := after[key]; !ok {
			continue // key absent in this deployment's config
		}
		beforeJSON, _ := json.Marshal(before[key])
		afterJSON, _ := json.Marshal(after[key])
		if string(beforeJSON) != string(afterJSON) {
			t.Errorf("section %q changed outside the plugin block", key)
		}
	}
	// Comment preservation: comments outside the plugin block must survive.
	// Comments inside it are regenerated by renderPluginBlock by design.
	originalLines := strings.Split(string(original), "\n")
	blockStart, _, errFind := findPluginBlock(originalLines)
	if errFind != nil {
		t.Fatalf("locate plugin block: %v", errFind)
	}
	blockEnd := pluginBlockEnd(originalLines, blockStart, indentOf(originalLines[blockStart]))
	for i, line := range originalLines {
		if i >= blockStart && i < blockEnd {
			continue
		}
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "#") {
			continue
		}
		if !strings.Contains(string(written), trimmed) {
			t.Errorf("comment lost: %q", trimmed)
			break
		}
	}
}

